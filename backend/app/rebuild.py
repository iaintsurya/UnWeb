import json
from bs4 import BeautifulSoup

def make_reconstruction(base_url: str, html: str) -> dict[str,str]:
    """Generate a safe, editable React outline; this does not recover original source."""
    soup = BeautifulSoup(html, "html.parser")
    for tag in soup(["script","style","noscript","iframe","object","embed","form"]):
        tag.decompose()
    for tag in soup.find_all(True):
        for attr in list(tag.attrs):
            if attr.lower().startswith("on") or attr.lower() in {"srcdoc","style"}:
                del tag.attrs[attr]
    title = soup.title.get_text(" ",strip=True) if soup.title else "Reconstructed page"
    body = soup.body or soup
    headings = [x.get_text(" ",strip=True)[:180] for x in body.find_all(["h1","h2","h3"])[:20]]
    paragraphs = [x.get_text(" ",strip=True)[:400] for x in body.find_all("p")[:30]]
    component = f"""import React from "react";
import "./reconstructed.css";

// Generated from observed page text. This is not original source code.
const headings: string[] = {json.dumps(headings,ensure_ascii=False,indent=2)};
const paragraphs: string[] = {json.dumps(paragraphs,ensure_ascii=False,indent=2)};

export default function ReconstructedPage() {{
  return <main className="page">
    <header><p className="eyebrow">UNWEB RECONSTRUCTION</p><h1>{json.dumps(title,ensure_ascii=False)}</h1></header>
    <section>{{headings.map((heading, i) => <article key={{i}}><h2>{{heading}}</h2>{{paragraphs[i] && <p>{{paragraphs[i]}}</p>}}</article>)}}</section>
    {{headings.length === 0 && paragraphs.map((p, i) => <p key={{i}}>{{p}}</p>)}}
    <footer>Generated by UnWeb · Edit this component freely</footer>
  </main>;
}}
"""
    css = """:root{font-family:Inter,system-ui,sans-serif;color:#20242c;background:#f5f5f2}
*{box-sizing:border-box}.page{max-width:1080px;margin:auto;padding:48px 28px}
header{border-bottom:1px solid #d9dee7;padding-bottom:28px;margin-bottom:32px}
.eyebrow{font:600 11px ui-monospace,monospace;letter-spacing:.12em;color:#a66b1e}
h1{font-size:clamp(2rem,5vw,4rem);letter-spacing:-.04em;line-height:1.05}
section{display:grid;gap:18px}article{border:1px solid #e1e5eb;border-radius:8px;padding:22px}
article p{color:#536071;line-height:1.7}footer{margin-top:40px;padding-top:16px;border-top:1px solid #d9dee7;color:#788394;font:12px ui-monospace,monospace}
"""
    return {"App.tsx":component,"reconstructed.css":css,"README.md":f"# Reconstructed starter\n\nGenerated from observed text and headings at {base_url}. It is not pixel-perfect or original source. Review rights and content before publishing.\n"}
